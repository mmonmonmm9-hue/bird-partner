const ALIAS: [RegExp, string][] = [
  [/กทม\.?|กรุงเทพ(?:ฯ|มหานคร)?/, 'กรุงเทพมหานคร'],
  [/อยุธยา/, 'พระนครศรีอยุธยา'],
  [/โคราช/, 'นครราชสีมา'],
  [/korat/i, 'นครราชสีมา'],
]

export function findProvince(text: string): string | undefined {
  for (const [re, name] of ALIAS) if (re.test(text)) return name
  return [...PROVINCES].sort((a, b) => b.length - a.length).find((p) => text.includes(p))
}
